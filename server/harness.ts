// local addition: which coding agent runs the Director: Claude Code, Qwen Code or OpenCode (the "harness" setting).
// The crew folder stays one source: CLAUDE.md and .claude/agents are mirrored to what the others read (QWEN.md and
// .qwen/agents for Qwen Code; AGENTS.md and .opencode/agent for OpenCode) every time the Director starts on them.
// Skills are SKILL.md folders in ~/.claude/skills: the mirrored agents name their folders, so any agent can read them.
// How each is driven:
//   claude, qwen  one process per conversation, messages in and events out as stream-json (the same format)
//   opencode      one `opencode run --format json` per message, continued with -s <session>
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import { config, saveConfig, baseDir } from './config.js';
import { findClaude } from './terminal.js';

const SKILLS = () => path.join(os.homedir(), '.claude', 'skills');
const NOTE = 'Generated by VideoHub from CLAUDE.md / .claude/agents: edit those, not this file.';
// a command on PATH; an npm launcher (.cmd) becomes "node <its script>" so it starts without a shell
export function which(name, env = process.env) {
  for (const dir of String(env.PATH || '').split(path.delimiter).filter(Boolean)) {
    for (const ext of process.platform === 'win32' ? ['.exe', '.cmd', ''] : ['']) {
      const f = path.join(dir, name + ext); if (!fs.existsSync(f) || fs.statSync(f).isDirectory()) continue;
      if (ext === '.cmd') { const m = /"%dp0%\\([^"]+)"\s+%\*/.exec(fs.readFileSync(f, 'utf8')); if (m) { const js = path.join(dir, m[1]); if (fs.existsSync(js)) return [process.execPath, js]; } continue; }
      if (ext === '' && process.platform === 'win32') continue;   // the sh launcher next to the .cmd
      return [f];
    }
  }
  return null;
}
const frontMatter = text => { const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/.exec(text); if (!m) return { fm: {}, body: text }; return { fm: Object.fromEntries(m[1].split(/\r?\n/).filter(l => l.includes(':')).map(l => [l.slice(0, l.indexOf(':')).trim(), l.slice(l.indexOf(':') + 1).trim()])), body: m[2] }; };
const skillsLine = s => s ? `\nYour skills are folders with a SKILL.md: ${s.split(',').map(x => x.trim()).filter(Boolean).map(x => path.join(SKILLS(), x, 'SKILL.md')).join(', ')}. Read the ones you need before you start.\n` : '';

// the crew folder in the files this coding agent reads
export function mirror(id, crew) {
  const claudeMd = path.join(crew, 'CLAUDE.md'), agents = path.join(crew, '.claude', 'agents');
  const instructions = fs.existsSync(claudeMd) ? fs.readFileSync(claudeMd, 'utf8') : '';
  const list = fs.existsSync(agents) ? fs.readdirSync(agents).filter(f => f.endsWith('.md')) : [];
  const write = (f, t) => { fs.mkdirSync(path.dirname(f), { recursive: true }); fs.writeFileSync(f, t); };
  if (id === 'qwen') {
    write(path.join(crew, 'QWEN.md'), `<!-- ${NOTE} -->\n${instructions}`);
    for (const f of list) { const { fm, body } = frontMatter(fs.readFileSync(path.join(agents, f), 'utf8')); write(path.join(crew, '.qwen', 'agents', f), `---\nname: ${fm.name || f.slice(0, -3)}\ndescription: ${fm.description || ''}\n---\n<!-- ${NOTE} -->\n${skillsLine(fm.skills)}\n${body}`); }
  }
  if (id === 'opencode') {
    write(path.join(crew, 'AGENTS.md'), `<!-- ${NOTE} -->\n${instructions}`);
    for (const f of list) { const { fm, body } = frontMatter(fs.readFileSync(path.join(agents, f), 'utf8')); write(path.join(crew, '.opencode', 'agent', f), `---\ndescription: ${fm.description || ''}\nmode: subagent\n---\n<!-- ${NOTE} -->\n${skillsLine(fm.skills)}\n${body}`); }
  }
}

export const HARNESSES = {
  claude: { label: 'Claude Code', find: () => { const c = findClaude(); return c ? [c] : null; }, kind: 'stream', site: 'claude.ai/install',
    args: ({ resume, mode }) => ['-p', '--input-format', 'stream-json', '--output-format', 'stream-json', '--verbose', '--include-partial-messages', '--permission-prompt-tool', 'stdio', '--add-dir', baseDir(), '--permission-mode', mode, ...(resume ? ['--resume', resume] : [])],
    terminal: () => ['--add-dir', baseDir()] },
  qwen: { label: 'Qwen Code', find: () => which('qwen'), kind: 'stream', site: 'github.com/QwenLM/qwen-code',
    args: ({ resume, mode }) => ['--input-format', 'stream-json', '--output-format', 'stream-json', '--include-partial-messages', '--add-dir', baseDir(), '--approval-mode', mode === 'auto' ? 'yolo' : 'auto-edit', ...(resume ? ['--resume', resume] : [])],
    terminal: () => ['--add-dir', baseDir()] },
  opencode: { label: 'OpenCode', find: () => which('opencode'), kind: 'run', site: 'opencode.ai',
    run: (text, session) => ['run', '--format', 'json', ...(session ? ['--session', session] : []), text],
    terminal: () => [] },
};
export const current = () => HARNESSES[config().harness] ? config().harness : 'claude';
export const list = () => Object.entries(HARNESSES).map(([id, x]) => ({ id, label: x.label, found: !!x.find(), site: x.site, active: id === current() }));
export function use({ id }: { id?: any } = {}) { if (!HARNESSES[id]) throw Object.assign(new Error('Unknown coding agent: ' + id), { code: 400 }); saveConfig({ harness: id }); return { harness: id }; }

// one OpenCode JSON event → chat events (exported for the tests)
export function openCodeEvents(m) {
  const p = m.part || {};
  if (m.type === 'text' && p.text?.trim()) return [{ kind: 'text', text: p.text }];
  if (m.type === 'tool_use') { const i = p.state?.input || {}; return [{ kind: 'tool', id: p.callID || p.id, name: p.tool || 'tool', text: String(i.description || i.command || i.filePath || i.pattern || i.url || '').slice(0, 160) }]; }
  if (m.type === 'error') return [{ kind: 'result', ok: false, text: String(m.error?.data?.message || m.error?.name || 'error').slice(0, 600) }];
  return [];
}
